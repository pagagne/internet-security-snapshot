"""Assembles "The Snapshot", the study's single manual (author's request, 29 Oct 2026).

Every document listed in config/manual.yaml is copied in full, in order, under its part. Each
document's own headings move down two levels (part = level 1, document = level 2), links to
other repository files become full GitHub links, and pictures point back to docs/. The result,
docs/manual/THE_SNAPSHOT.md, is generated: never edit it by hand. Checks fails if it is stale.

  python -m snapshot.manual build
  python -m snapshot.manual check
"""
from __future__ import annotations

import argparse
import glob
import re
import sys
from pathlib import Path

import yaml

from .util import _repo_root

CONFIG = "config/manual.yaml"
REPO_URL = "https://github.com/pagagne/internet-security-snapshot/blob/main/"
LINK = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)\)")


def load(root: Path) -> dict:
    return yaml.safe_load((root / CONFIG).read_text())


def expand(root: Path, patterns: list[str]) -> list[str]:
    out = []
    for p in patterns:
        hits = sorted(Path(x).relative_to(root).as_posix() for x in glob.glob(str(root / p)))
        if not hits:
            raise FileNotFoundError(f"{CONFIG}: nothing matches {p}")
        out += [h for h in hits if h not in out]
    return out


def all_docs(root: Path, cfg: dict) -> list[str]:
    return [d for part in cfg["parts"] for d in expand(root, part["docs"])]


def _anchor(path: str) -> str:
    return "doc-" + re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")


def _fix_links(text: str, src: str, out_dir: str, included: set[str]) -> str:
    base = Path(src).parent

    def sub(m):
        bang, label, target = m.groups()
        if re.match(r"^[a-z]+:|^#|^mailto:", target):
            return m.group(0)
        path, _, frag = target.partition("#")
        resolved = Path(base, path).as_posix()
        resolved = re.sub(r"(^|/)\./", r"\1", resolved)
        while "/../" in "/" + resolved:
            resolved = re.sub(r"[^/]+/\.\./", "", resolved, count=1)
        if bang:                                   # picture: keep it local, relative to the manual
            rel = Path(*([".."] * len(Path(out_dir).parts)), resolved).as_posix()
            return f"![{label}]({rel})"
        if resolved in included and not frag:
            return f"[{label}](#{_anchor(resolved)})"
        return f"[{label}]({REPO_URL}{resolved}{'#' + frag if frag else ''})"
    return LINK.sub(sub, text)


def _shift_headings(text: str, by: int = 2) -> str:
    out, fence = [], False
    for line in text.split("\n"):
        if line.lstrip().startswith(("```", "~~~")):
            fence = not fence
        if not fence and re.match(r"^#{1,6} ", line):
            hashes = len(line) - len(line.lstrip("#"))
            line = "#" * min(6, hashes + by) + line[hashes:]
        out.append(line)
    return "\n".join(out)


def _title(text: str, path: str) -> str:
    m = re.search(r"^# (.+)$", text, re.M)
    return m.group(1).strip() if m else path


def build_text(root: Path | None = None) -> str:
    root = root or _repo_root()
    cfg = load(root)
    out_dir = str(Path(cfg["output"]).parent)
    parts = [(p["name"], expand(root, p["docs"])) for p in cfg["parts"]]
    included = {d for _, docs in parts for d in docs}
    L = [f"# {cfg['title']}", "", f"**{cfg['subtitle']}**", "",
         "Generated from the study's documents by `python -m snapshot.manual build` (config: "
         f"`{CONFIG}`). Do not edit this file: change the source document and rebuild. Each "
         "section names its source file; the repository is the single source of truth.", "",
         "## Contents", ""]
    for name, docs in parts:
        L.append(f"- **{name}**")
        for d in docs:
            L.append(f"  - [{_title((root / d).read_text(), d)}](#{_anchor(d)}) (`{d}`)")
    L.append("")
    for name, docs in parts:
        L += ["", f"# {name}", ""]
        for d in docs:
            text = (root / d).read_text().strip()
            title = _title(text, d)
            body = re.sub(r"^# .+\n?", "", text, count=1, flags=re.M) if text.startswith("# ") else text
            L += ["", f'<a id="{_anchor(d)}"></a>', "", f"## {title}", "",
                  f"*Source: [`{d}`]({REPO_URL}{d})*", "",
                  _shift_headings(_fix_links(body, d, out_dir, included)).strip(), ""]
    return "\n".join(L).rstrip() + "\n"


def unlisted(root: Path | None = None) -> list[str]:
    """Markdown files in the repository that are neither in the manual nor excluded."""
    import subprocess
    root = root or _repo_root()
    cfg = load(root)
    files = subprocess.run(["git", "ls-files", "*.md"], cwd=root, capture_output=True, text=True).stdout.split()
    known = set(all_docs(root, cfg)) | set(cfg.get("excluded", {}))
    return [f for f in files if f not in known and not f.startswith("tests/")]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["build", "check"])
    a = ap.parse_args(argv)
    root = _repo_root()
    out = root / load(root)["output"]
    text = build_text(root)
    if a.cmd == "build":
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        print(f"{out.relative_to(root)}: {len(text.split()):,} words")
        return 0
    missing = unlisted(root)
    if missing:
        print("Not in the manual (add to config/manual.yaml, or to `excluded` with a reason): " + ", ".join(missing))
        return 1
    if not out.exists() or out.read_text() != text:
        print("The manual is out of date: run `python -m snapshot.manual build` and commit it.")
        return 1
    print("manual is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
