"""Exploratory X30 and X31 readings (author's decisions, 19 Nov 2026; schedule item x30-x31-build).

X30, AI software supply chain: OpenSSF malicious-packages records (github.com/ossf/malicious-packages,
Apache-2.0, the source OSV's MAL- records come from) for npm and PyPI, counted per quarter by the
record's publication date, all records and those whose package name or summary names an AI provider,
library or agent tool (config/x30_ai_terms.yaml). Only caught and reported packages are counted.

X31, AI-generated reports and capacity to fix: per quarter, CVE records rejected (by their rejection
date) and published records the CNA tagged "disputed", from the CVE List; for rejections, a flag for
reasons that mention AI or language models (one signal among many causes; never proof).

Counts and identifiers only; the advisory texts are not kept. Results go to the private repository.

    python -m snapshot.research.x30_x31 --out DIR
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import tempfile
from pathlib import Path

import pandas as pd

from ..util import load_config

MAL_REPO = "https://github.com/ossf/malicious-packages"
CVE_REPO = "https://github.com/CVEProject/cvelistV5"
ECOSYSTEMS = ("npm", "pypi")
AI_REASON = re.compile(r"\b(?:AI|A\.I\.|LLM|large language model|ChatGPT|generated by an? (?:AI|LLM|tool)|hallucinat\w*)\b", re.I)


def quarter(ts: pd.Series) -> pd.Series:
    t = pd.to_datetime(ts, utc=True, errors="coerce")
    return t.dt.year.astype("Int64").astype(str) + "Q" + t.dt.quarter.astype("Int64").astype(str)


def ai_terms() -> tuple[str, set[str]]:
    c = load_config("x30_ai_terms.yaml")
    return str(c["version"]), {t.lower() for t in c["terms"]}


def ai_match(name: str, summary: str, terms: set[str]) -> list[str]:
    parts = set(re.split(r"[-_./@\s]+", (name or "").lower()))
    words = set(re.findall(r"[a-z0-9]+", (summary or "").lower().replace(f"malicious code in {name.lower()}", "")))
    return sorted(t for t in terms if t in parts or (len(t) > 3 and t in words))


def malicious_rows(root: Path, terms: set[str]) -> pd.DataFrame:
    rows = []
    for eco in ECOSYSTEMS:
        for p in (root / "osv/malicious" / eco).rglob("*.json"):
            try:
                d = json.loads(p.read_text())
            except (ValueError, OSError):
                continue
            pkg = ((d.get("affected") or [{}])[0].get("package") or {})
            name = pkg.get("name", "")
            hit = ai_match(name, d.get("summary", ""), terms)
            rows.append({"id": d.get("id"), "ecosystem": eco, "package": name, "published": d.get("published"),
                         "withdrawn": bool(d.get("withdrawn")), "ai_terms": ";".join(hit)})
    return pd.DataFrame(rows)


def cve_rows(root: Path) -> pd.DataFrame:
    rows = []
    for p in (root / "cves").rglob("CVE-*.json"):
        try:
            d = json.loads(p.read_text())
        except (ValueError, OSError):
            continue
        m = d.get("cveMetadata") or {}
        cna = (d.get("containers") or {}).get("cna") or {}
        if m.get("state") == "REJECTED":
            reasons = " ".join(r.get("value", "") for r in cna.get("rejectedReasons") or [])
            rows.append({"cve": m.get("cveId"), "kind": "rejected", "date": m.get("dateRejected") or m.get("dateUpdated"),
                         "assigner": m.get("assignerShortName"), "ai_reason": bool(AI_REASON.search(reasons))})
        elif "disputed" in (cna.get("tags") or []):
            rows.append({"cve": m.get("cveId"), "kind": "disputed", "date": m.get("datePublished"),
                         "assigner": m.get("assignerShortName"), "ai_reason": False})
    return pd.DataFrame(rows)


def summarise(mal: pd.DataFrame, cves: pd.DataFrame, since: str = "2024Q1") -> dict:
    out: dict = {}
    if len(mal):
        m = mal[~mal["withdrawn"]].assign(q=quarter(mal["published"]))
        m = m[m["q"] >= since]
        g = m.groupby(["q", "ecosystem"]).agg(all=("id", "size"), ai=("ai_terms", lambda s: int((s != "").sum())))
        out["x30"] = {f"{q} {e}": {"all": int(r["all"]), "ai": int(r["ai"])} for (q, e), r in g.iterrows()}
    if len(cves):
        c = cves.assign(q=quarter(cves["date"]))
        c = c[c["q"] >= since]
        g = c.groupby(["q", "kind"]).agg(n=("cve", "size"), ai_reason=("ai_reason", "sum"))
        out["x31"] = {f"{q} {k}": {"n": int(r["n"]), "ai_reason": int(r["ai_reason"])} for (q, k), r in g.iterrows()}
    return out


def _clone(url: str, dest: Path, sparse: list[str]) -> str:
    subprocess.run(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "--sparse", url, str(dest)], check=True)
    subprocess.run(["git", "-C", str(dest), "sparse-checkout", "set", *sparse], check=True)
    return subprocess.run(["git", "-C", str(dest), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--start"); ap.add_argument("--end")   # accepted for the research workflow; unused
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args(argv)
    a.out.mkdir(parents=True, exist_ok=True)
    version, terms = ai_terms()
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        mal_sha = _clone(MAL_REPO, t / "mal", [f"osv/malicious/{e}" for e in ECOSYSTEMS])
        mal = malicious_rows(t / "mal", terms)
        cve_sha = _clone(CVE_REPO, t / "cve", ["cves"])
        cves = cve_rows(t / "cve")
    mal.to_csv(a.out / "x30_malicious_packages.csv", index=False)
    cves.to_csv(a.out / "x31_rejected_disputed.csv", index=False)
    S = summarise(mal, cves)
    S.update({"malicious_packages_commit": mal_sha, "cve_list_commit": cve_sha, "ai_terms_version": version})
    (a.out / "x30_x31.json").write_text(json.dumps(S, indent=1))
    L = ["# X30 and X31 readings (exploratory, private)", "",
         f"Malicious-packages commit {mal_sha}; CVE List commit {cve_sha}; AI terms {version}.", "",
         "## X30: malicious packages per quarter (all / naming AI)", ""]
    L += [f"- {k}: {v['all']} / {v['ai']}" for k, v in sorted(S.get("x30", {}).items())]
    L += ["", "## X31: rejected and disputed CVE records per quarter (n / reason mentions AI)", ""]
    L += [f"- {k}: {v['n']} / {v['ai_reason']}" for k, v in sorted(S.get("x31", {}).items())]
    (a.out / "summary.md").write_text("\n".join(L) + "\n")
    print("x30_x31 done")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
