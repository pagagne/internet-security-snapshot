"""Catalogue of AI attack methods and register of resources, generated from the X3 log.

Author's decision, 29 Oct 2026 (12 Nov research review item 13, decided early, option B): the
AI-attack log `exploratory/ai_attack_campaigns.csv` carries two extra columns, `attack_method`
(a fixed list, below) and `found_via` (how the case reached the study). This module builds
`exploratory/ai_attack_catalogue.md` from the log, so the catalogue and the resource register
never drift from it. Exploratory and never scored: the counts reflect what gets reported.

  python -m snapshot.x3catalogue build
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlparse

from .util import _repo_root

LOG = "exploratory/ai_attack_campaigns.csv"
OUT = "exploratory/ai_attack_catalogue.md"
SWEEP_CFG = "config/exploratory.yaml"

METHODS = {   # fixed list (29 Oct 2026); additions are dated here and in config/exploratory.yaml
    "autonomous_intrusion": "AI agents carry out an intrusion largely on their own (scouting, exploiting, staying in)",
    "agent_recon": "AI agents used only to scout targets and test which flaws work",
    "credential_harvest": "AI agents harvest or test stolen logins and keys at scale",
    "ai_planned_human_led": "AI writes the attack plan or advises; a person carries it out",
    "ai_written_tooling": "AI writes the malware, exploits or scripts a person then uses",
    "ai_system_hijack": "The victim's own AI assistant or agent is hijacked or tricked (e.g. hidden instructions)",
    "compute_theft": "Exposed AI servers or accounts are taken over for their computing power (LLMjacking)",
    "ai_social_engineering": "AI-made lures, voices or faces used to deceive people",
    "evaluation_escape": "An AI model under test reaches real systems with no attacker directing it (logged beside campaigns)",
    "other": "Anything else; reviewed for a new category at the March review",
}
FOUND_VIA = {
    "author": "forwarded by the author",
    "quarterly_sweep": "the quarterly search (X3 sweep)",
    "trial_sweep": "the trial search of 26 Oct 2026",
    "feed_screen": "the monthly feed screen (from Nov 2026)",
    "newsletter": "a newsletter read in the project inbox (from Nov 2026)",
    "conference": "a conference talk (twice-yearly scan, from Jan 2027)",
    "claude_research": "Claude's research when the log was set up",
}


def load(root: Path) -> list[dict]:
    return list(csv.DictReader((root / LOG).open()))


def _reporter(r: dict) -> str:
    return re.split(r"[(;,]| via ", r["reported_by"])[0].strip()


def build_text(root: Path | None = None) -> str:
    root = root or _repo_root()
    rows = load(root)
    sweep = (root / SWEEP_CFG).read_text().lower()
    n = len(rows)
    L = ["# AI attack methods and resources (generated)", "",
         f"Generated by `python -m snapshot.x3catalogue build` from `{LOG}` ({n} cases). Do not edit: "
         "change the log and rebuild. Exploratory, never scored; counts reflect what organisations "
         "chose to report, not everything that happened. Evaluation escapes are listed beside "
         "campaigns and never counted as one.", "",
         "## Attack methods", "",
         "| Method | What it means | Cases | Confirmed AI use | Through a named CVE | First reported | Examples |",
         "|---|---|---|---|---|---|---|"]
    by = defaultdict(list)
    for r in rows:
        by[r["attack_method"]].append(r)
    for m, desc in METHODS.items():
        rs = by.get(m, [])
        if not rs:
            L.append(f"| `{m}` | {desc} | 0 | - | - | - | - |")
            continue
        conf = sum(r["ai_evidence"] == "confirmed" for r in rs)
        cve = sum(bool(r["cve_ids"]) or r["entry_vector"] == "known_cve" for r in rs)
        ex = "; ".join(r["campaign"].split(" (")[0][:60] for r in sorted(rs, key=lambda r: r["date_reported"])[:2])
        L.append(f"| `{m}` | {desc} | {len(rs)} | {conf} | {cve} | {min(r['date_reported'] for r in rs)} | {ex} |")
    cve_all = sum(bool(r["cve_ids"]) or r["entry_vector"] == "known_cve" for r in rows)
    L += ["", f"Only {cve_all} of {n} cases entered through a flaw with a CVE number, the kind the "
          "study's core measures can see; the rest came in through passwords, misconfigurations, "
          "phishing, zero-days or unknown routes. \"Confirmed\" counts only rows the author has "
          "rated (`ai_evidence`); unrated rows are not counted as confirmed.", "",
          "## Resource register", "",
          "Every organisation whose report is in the log, how its cases reached the study, and "
          "whether it is already on the quarterly search's fixed list (`config/exploratory.yaml`, X3).", "",
          "| Reporter | Site | Cases | Found via | First case | On the sweep list |",
          "|---|---|---|---|---|---|"]
    rep = defaultdict(list)
    for r in rows:
        rep[_reporter(r)].append(r)
    for name in sorted(rep, key=lambda k: (-len(rep[k]), k)):
        rs = rep[name]
        sites = sorted({urlparse(r["source_url"]).netloc.removeprefix("www.") for r in rs})
        via = sorted({FOUND_VIA.get(r["found_via"], r["found_via"]) for r in rs})
        key = name.split()[0].lower()
        listed = "yes" if len(key) > 2 and key in sweep else "no"
        L.append(f"| {name} | {', '.join(sites)} | {len(rs)} | {'; '.join(via)} | "
                 f"{min(r['date_reported'] for r in rs)} | {listed} |")
    L += ["", "How cases reached the study: " + "; ".join(
        f"{FOUND_VIA[k]} {sum(r['found_via'] == k for r in rows)}" for k in FOUND_VIA
        if any(r["found_via"] == k for r in rows)) + "."]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["build", "check"])
    a = ap.parse_args(argv)
    root = _repo_root()
    text = build_text(root)
    out = root / OUT
    if a.cmd == "build":
        out.write_text(text)
        print(f"{OUT}: {len(load(root))} cases")
        return 0
    if not out.exists() or out.read_text() != text:
        print(f"{OUT} is out of date: run `python -m snapshot.x3catalogue build`.")
        return 1
    print("catalogue is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
